import { writeFile } from 'node:fs/promises'
import path from 'node:path'

const outPath = path.resolve('lib/published-blog-slugs.generated.ts')

function normalizeWpApiUrl(input) {
  const trimmed = input.trim().replace(/\/+$/, '')
  if (trimmed.endsWith('/wp-json')) return trimmed
  return `${trimmed}/wp-json`
}

async function fetchAllSlugs(apiBase) {
  const slugs = new Set()
  let page = 1
  for (;;) {
    const url = `${apiBase}/wp/v2/posts?per_page=100&page=${page}&status=publish&_fields=slug`
    const res = await fetch(url)
    if (!res.ok) break
    const posts = await res.json()
    if (!Array.isArray(posts) || posts.length === 0) break
    for (const post of posts) {
      if (post && typeof post.slug === 'string') slugs.add(post.slug)
    }
    if (posts.length < 100) break
    page += 1
  }
  return slugs
}

const raw = process.env.NEXT_PUBLIC_WP_API_URL
if (!raw) {
  await writeFile(
    outPath,
    `/** Generated at build time; empty when NEXT_PUBLIC_WP_API_URL is unset. */\nexport const publishedBlogSlugs = new Set<string>()\n`,
  )
  console.log('generate-published-blog-slugs: skipped (no NEXT_PUBLIC_WP_API_URL)')
  process.exit(0)
}

try {
  const apiBase = normalizeWpApiUrl(raw)
  const slugs = await fetchAllSlugs(apiBase)
  const list = [...slugs].sort()
  const body = `/** Generated by scripts/generate-published-blog-slugs.mjs — do not edit. */
export const publishedBlogSlugs = new Set<string>([
${list.map((s) => `  ${JSON.stringify(s)},`).join('\n')}
])
`
  await writeFile(outPath, body)
  console.log(`generate-published-blog-slugs: wrote ${list.length} slugs`)
} catch (error) {
  console.warn('generate-published-blog-slugs: failed, writing empty set', error)
  await writeFile(
    outPath,
    `/** Generated at build time; empty after generation failure. */\nexport const publishedBlogSlugs = new Set<string>()\n`,
  )
}
